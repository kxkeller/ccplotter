def test_route_two_files_headers_and_safety(job):
    j = job["resp"]
    assert [g["color"] for g in j["gcode_files"]] == ["blue", "black"]
    for color, text in job["text"].items():
        code = "\n".join(l.split(";")[0] for l in text.splitlines())
        assert not re.search(r"\bG92\b", code) and not re.search(r"\bM106\s+P[01]\b", code)
        assert not re.search(r"^\s*(M0|M1|M600|M25|M226)\b", code, re.M)
        assert len([l for l in text.splitlines() if l.startswith("; PASS")]) == 1
        assert "; PAIR " in text and "; PLACEMENT shared" in text and "; PEN this_pass" in text
        assert text.count("M117 Plotting...") == 1 and text.count("M117 Plot complete") == 1
    assert "PASS 1 OF 2: BLUE" in job["text"]["blue"] and "PASS 2 OF 2: BLACK" in job["text"]["black"]
    assert all(g["reach_validated"] for g in j["gcode_files"])
    assert all(g["time_est"]["label"] == "model (b), not stopwatch-validated" for g in j["gcode_files"])


def test_route_strokes_match_the_recipe_and_hash(job):
    tw = job["resp"]["twotone"]
    ref = REF["default_257x182"]["dahlia"]
