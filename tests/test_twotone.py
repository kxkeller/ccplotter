def test_fixture_inputs_are_the_ones_the_reference_was_made_from_and_small():
    for n, sha in REF["inputs_sha256"].items():
        p = FIX / f"{n}.jpg"
        assert hashlib.sha256(p.read_bytes()).hexdigest() == sha, n
        assert p.stat().st_size < 1_000_000, (n, p.stat().st_size)


@pytest.mark.parametrize("name", ["dahlia", "pagoda", "synth"])
def test_parity_with_recipe_frozen_default_page(name):
    L = tt.generate_layers(FIX / f"{name}.jpg")            # default page 257x182, margin 10
    ref = REF["default_257x182"][name]
    assert (len(L["blue"]), len(L["lines"]), len(L["shadow"])) == (ref["n_blue"], ref["n_black"], ref["n_shadow"])
    assert L["hash"] == ref["hash"]


def test_parity_with_recipe_frozen_legacy_257x176_page():
    """257x176 with a 10 mm margin is exactly the legacy placement (live 237x156 centred at 128.5, 88)."""
    L = tt.generate_layers(FIX / "dahlia.jpg", page=(257.0, 176.0))
    assert L["hash"] == REF["legacy_257x176"]["dahlia"]["hash"]


def test_parity_check_can_fail():
    """Negative control: a different page changes the placement, so the hash must differ from the default reference."""
    L = tt.generate_layers(FIX / "dahlia.jpg", page=(257.0, 176.0))
    assert L["hash"] != REF["default_257x182"]["dahlia"]["hash"]
    assert REF["default_257x182"]["dahlia"]["hash"] != REF["legacy_257x176"]["dahlia"]["hash"]


def test_only_the_light_preset_exists_and_others_are_refused():
    assert tt.PRESETS == ("LIGHT",)
    for bad in ("MEDIUM", "HEAVY", "x"):
        with pytest.raises(ValueError):
            tt.generate_layers(FIX / "dahlia.jpg", blue_preset=bad)


def test_layers_are_mm_page_coordinates_inside_the_live_area():
    L = tt.generate_layers(FIX / "dahlia.jpg")
    xs = [p[0] for col in ("blue", "black") for s in L[col] for p in s]
    ys = [p[1] for col in ("blue", "black") for s in L[col] for p in s]
    assert 10.0 - 1e-6 <= min(xs) and max(xs) <= 257.0 - 10.0 + 1e-6
    assert 10.0 - 1e-6 <= min(ys) and max(ys) <= 182.0 - 10.0 + 1e-6
    for col in ("blue", "black"):                      # every hatch/line stroke >= 2 mm except black Canny pieces (>= 2.5)
        assert all(len(s) >= 2 for s in L[col])
    assert L["black"] == L["lines"] + L["shadow"]


