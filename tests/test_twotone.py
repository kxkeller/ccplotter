# ------------------------------------------------------------------ gate, recording, provenance
def test_texture_gate_artefacts_readouts_and_provenance(job):
    from ccplotter.runs import load_run_provenance, _runs_load
    j = job["resp"]
    tg = j["texture_gate"]
    assert set(tg) == {"dropped_strokes", "dropped_ink_mm", "dropped_ink_fraction"}
    assert tg["dropped_strokes"] >= 0 and tg["dropped_ink_mm"] >= 0.0 and 0.0 <= tg["dropped_ink_fraction"] <= 1.0
    assert j["twotone"]["texture_gate"] == tg
    # artefacts exist in the job dir
    a = j["twotone"]["gate_artefacts"]
    png, dj = Path(a["map_png"]), Path(a["dropped_json"])
    assert png.is_file() and dj.is_file() and str(png.parent).startswith(str(WORK_DIR))
    import cv2
    im = cv2.imread(str(png), cv2.IMREAD_UNCHANGED)
    assert im is not None and set(int(v) for v in set(im.ravel().tolist())) <= {0, 255}
    dropped = json.loads(dj.read_text())["strokes"]
    assert len(dropped) == tg["dropped_strokes"]
    # readouts: realised per-job adaptive quantities
    ro = j["twotone"]["readouts"]
    for k in ("p2", "canny_high", "canny_low", "gate_density_threshold", "shadow_band_threshold"):
        assert k in ro and isinstance(ro[k], float), k
    assert ro["canny_low"] == pytest.approx(0.4 * ro["canny_high"], rel=1e-3) and 0.0 <= ro["p2"] <= 255.0
    # run record and provenance carry them
    rec = next(r for r in _runs_load() if r["id"] == j["run_id"])
    assert rec["texture_gate"] == tg and rec["twotone"]["readouts"] == ro
    res = load_run_provenance(j["run_id"])["resolved"]["twotone"]
    assert res["readouts"] == ro and res["texture_gate"] == tg and res["hash"] == j["twotone"]["hash"]


def test_texture_gate_numbers_are_real_and_do_not_change_the_hash():
    """The gate drops something on a busy image (not a constant 0), and recording it leaves the stroke hash at the reference."""
    L = tt.generate_layers(FIX / "pagoda.jpg")
    tgc = L["texture_gate"]
    assert tgc["dropped_strokes"] > 0 and 0.0 < tgc["dropped_ink_fraction"] < 1.0
    assert tgc["dropped_strokes"] == len(L["gate_dropped"])
    assert L["hash"] == REF["default_257x182"]["pagoda"]["hash"]
    assert L["gate_map"].dtype == bool and L["gate_map"].any()


