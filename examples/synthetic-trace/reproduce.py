"""Reproduce this example against a running ccPlotter server.

1. Start the server with an isolated, empty, absolute runtime home (see README.md).
2. python reproduce.py --base-url http://127.0.0.1:5093 --out <dir>

Writes <dir>/output.gcode (two header comment lines normalised, see normalise_header), <dir>/preview.svg and <dir>/preview.png, and prints the
sha256 of the G-code. Uses only HTTP calls the web UI itself makes
(/api/add_drawing, /api/process, /work/<file>).
"""
import argparse
import copy
import hashlib
import json
import sys
from pathlib import Path

import requests

HERE = Path(__file__).resolve().parent


def normalise_header(data: bytes) -> bytes:
    """Replace the two header comment lines that differ between runs.

    The server writes the absolute path of its work directory ("; Source: ...") and a
    random run id ("; ccplotter-run: id=...") into the first lines. Both are comments
    (no motion). They are replaced by fixed text so the file is comparable byte for
    byte; every other byte is exactly what the server produced.
    """
    out = []
    for line in data.splitlines(keepends=True):
        eol = line[len(line.rstrip(b"\r\n")):]
        if line.startswith(b"; Source: "):
            line = b"; Source: <runtime home>/work/layout.gcode" + eol
        elif line.startswith(b"; ccplotter-run: "):
            line = b"; ccplotter-run: <run id removed>" + eol
        out.append(line)
    return b"".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base-url", default="http://127.0.0.1:5093")
    ap.add_argument("--out", default=str(HERE / "reproduced"))
    a = ap.parse_args()
    base = a.base_url.rstrip("/")
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    spec = json.loads((HERE / "settings.json").read_text(encoding="utf-8"))

    # The server must be using the calibration and pen profile recorded in settings.json.
    cal = requests.get(f"{base}/api/calibration", timeout=30).json()
    pens = requests.get(f"{base}/api/pen_profiles", timeout=30).json()
    want = spec["calibration_in_effect"]["api_calibration_pen_reach"]
    got = {k: cal["pen_reach"].get(k) for k in want}
    if got != want:
        print("The server's reach differs from settings.json; refusing to continue.\n", got, "\n", want)
        return 2
    pid = spec["request"]["pen_id"]
    live = pens["profiles"][pid] if "profiles" in pens else pens[pid]
    for k, v in spec["pen_profile_in_effect"].items():
        if live.get(k) != v:
            print(f"Pen profile {pid!r} differs from settings.json at {k!r}: {live.get(k)!r} != {v!r}")
            return 2

    with open(HERE / "input.png", "rb") as fh:
        r = requests.post(f"{base}/api/add_drawing", files={"file": ("input.png", fh, "image/png")}, timeout=60)
    r.raise_for_status()
    did = r.json()["id"]

    results = {}
    for job_type in ("preview", "gcode"):
        body = copy.deepcopy(spec["request"])
        body["job_type"] = job_type
        body["items"][0]["id"] = did
        r = requests.post(f"{base}/api/process", json=body, timeout=1800)
        if r.status_code != 200:
            print(job_type, "failed:", r.status_code, r.text[:500])
            return 1
        results[job_type] = r.json()
        print(job_type, "ok:", {k: results[job_type].get(k) for k in ("stroke_count", "estimated_pen_lifts", "estimated_plot_time_min") if k in results[job_type]})

    res = results["gcode"]
    gcode = requests.get(f"{base}/work/{res['gcode_file']}", timeout=120).content
    svg = requests.get(f"{base}/work/{res['preview_file']}", timeout=120).content
    gcode = normalise_header(gcode)
    (out / "output.gcode").write_bytes(gcode)
    (out / "preview.svg").write_bytes(svg)
    try:
        import fitz  # PyMuPDF, already in requirements.txt
        doc = fitz.open(stream=svg, filetype="svg")
        doc[0].get_pixmap(dpi=96).save(str(out / "preview.png"))
        from PIL import Image, ImageDraw, ImageFont
        im = Image.open(out / "preview.png").convert("RGB")
        bar = 34
        lab = Image.new("RGB", (im.width, im.height + bar), "white")
        lab.paste(im, (0, bar))
        ImageDraw.Draw(lab).text((8, 8), "SOFTWARE PREVIEW - generated by ccPlotter, not a physical plot",
                                 fill=(160, 0, 0), font=ImageFont.load_default(size=16))
        lab.save(out / "preview.png", optimize=True)
    except Exception as e:  # preview.png is a convenience only
        print("preview.png not written:", e)
    print("sha256", hashlib.sha256(gcode).hexdigest(), "output.gcode", len(gcode), "bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
