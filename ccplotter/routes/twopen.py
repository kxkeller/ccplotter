"""ccplotter/routes/twopen.py -- POST /api/twopen (opt-in two-pen job).

Body: {blue_svg, black_svg (path or inline SVG), blue_pen_id, black_pen_id, paper,
       scale, rot, dx, dy (identical placement for both layers), paper_rot,
       offset_x, offset_y, microlift, end_policy, quiet_fans, motion_smoothing}.
z_up/z_down/speeds are NOT read from the body: they come from each pen profile.

LAYER UNITS: blue_svg / black_svg must be MM PAGE COORDINATES. The root <svg> needs width and
height in mm and a viewBox that is 1 user unit = 1 mm (or 1 CSS px, as vpype writes it); any
other SVG is refused with a 400, because it would be silently mis-scaled on paper.

Response/run record also carry a per-file plot-time estimate, "model (b), not stopwatch-
validated" (per-move length / feed, Z moves included; a floor, not a forecast).
Existing routes are untouched; registered by an import at the bottom of routes/core.py.
"""
import time
import traceback
from pathlib import Path
from uuid import uuid4

from flask import jsonify, request

from ccplotter.routes import app
from ccplotter.routes.core import _PROCESS_LOCK
from ccplotter.runs import _runs_add, build_run_provenance
from ccplotter.twopen import TwoPenRefusal, build_twopen, TWOPEN_DIRNAME


