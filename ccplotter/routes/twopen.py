def api_twopen_calsheet():
    """Two-pen calibration sheet "M10-REG v1" (opt-in; NOT in the one-file calibration
    registry). Body: {variant "A"|"B" (default B), blue_pen_id?, black_pen_id?, offset_x?, offset_y?, microlift?, end_policy?,
    quiet_fans?, motion_smoothing?}. The two layers are generated by ccplotter/calibration_twopen.py
    and pushed through the same twopen pipeline as a real job."""
    return _handle(request.get_json(silent=True), sheet=True)


SHEET_DEFAULT_PENS = {"A": ("bic_cristal_blue", "bic_cristal_blue_b"),
                      "B": ("bic_cristal_blue", "bic_cristal_black")}
SHEET_PASS_COLORS = ("#1f4fd8", "#e8590c")      # canvas preview: pass 1 blue, pass 2 orange (A has two blue pens)
SHEET_BLURB = {"A": "Pen-swap repeatability: same pen model twice (blue, then its duplicate profile).",
               "B": "Blue then black: laid widths and the overlay swatches."}


@app.route("/api/twopen_calsheet_info", methods=["GET"])
def api_twopen_calsheet_info():
    """Read-only catalogue for the UI: per variant, the preset pen ids/labels and whether each profile exists."""
    from ccplotter.cal import load_pen_profiles
    profs = load_pen_profiles().get("profiles", {})
    out = []
    for v, (p1, p2) in SHEET_DEFAULT_PENS.items():
        out.append({"variant": v, "blurb": SHEET_BLURB[v],
                    "pens": [{"pass": i + 1, "pen_id": pid, "label": (profs.get(pid) or {}).get("label") or pid,
                              "exists": pid in profs} for i, pid in enumerate((p1, p2))]})
    return jsonify({"sheets": out})


def _sheet_canvas_preview(r, rid):
    """Sheet only: a two-colour (pass 1 blue / pass 2 orange) preview SVG in WORK_DIR for the canvas, plus the
    marker so canvas gcode of it is refused. Returns the svg file name."""
    import shlex
    import vpype_cli
    from ccplotter.atomic_io import atomic_target, atomic_write_bytes
    from ccplotter.config import WORK_DIR
    name = f"m10reg_{rid}.svg"
    with atomic_target(WORK_DIR / name) as tmp:
        vpype_cli.execute(
            f"read -l 1 {shlex.quote(r['layers']['blue'])} read -l 2 {shlex.quote(r['layers']['black'])} "
            f"color -l 1 {SHEET_PASS_COLORS[0]} color -l 2 {SHEET_PASS_COLORS[1]} "
            f"penwidth -l 1 0.4mm penwidth -l 2 0.4mm write {shlex.quote(str(tmp))}")
    atomic_write_bytes(WORK_DIR / f"calsheet_{Path(name).stem}.flag", b"1" + chr(10).encode())
    return name


def _sheet_provenance_shas(rid, r, variant):
    """Sheet only: add BOTH final gcode sha256s (as sideloaded, back-link included, plus the back-link-stripped
    sha the replay harness uses) to the run's provenance sidecar. Returns the sha dict."""
    import hashlib
    from ccplotter.runs import (_provenance_write, load_run_provenance, strip_run_backlink)
    shas = {}
    for n, color in ((1, "blue"), (2, "black")):
        data = r["files"][color].read_bytes()
        shas[f"pass{n}"] = {"file": r["files"][color].name, "sha256": hashlib.sha256(data).hexdigest(),
                            "sha256_without_backlink": hashlib.sha256(strip_run_backlink(data)).hexdigest(),
                            "bytes": len(data)}
    prov = load_run_provenance(rid)
    if prov is not None:
        prov["kind"] = "twopen_calsheet"
        prov["sheet_variant"] = variant
        prov["gcode_sha256"] = shas
        _provenance_write(rid, prov)
    return shas


@app.route("/api/twotone", methods=["POST"])
def api_twotone():
    """Opt-in: PHOTO -> fixed two-tone recipe (ccplotter/twotone.py, v16 default) -> two mm layers ->
    the same twopen pipeline (gcode x2, preview, run record, headers, refusals, tip window).
    Body: {image: <path to a photo>  OR  image_b64: <base64 file bytes>, blue_pen_id, black_pen_id,
    blue_preset ("LIGHT" only), paper ("257x182" default), margin (10), and the twopen placement fields
    (offset_x, offset_y, scale, rot, dx, dy, paper_rot, tip_window, microlift, end_policy, quiet_fans,
    motion_smoothing)}. /api/process, /api/twopen and every existing mode are untouched.

    KEEP-OUT: /api/twotone applies NO hole-strip keep-out and no paper-window check of its own. The
    only margin is the generator's `margin` (10 mm all round). The CALLER must pass the registered placement
    (offset_x / offset_y) and a `tip_window` for the paper; a request without them is placed at the reach-bbox
    default and is not checked against any paper edge or punched-hole strip.

    Per-job artefacts in WORK_DIR/twotone/<run id>/: texture_gate.png (the density-above-threshold gate
    map), texture_gate_dropped.json (the black strokes the gate dropped, mm page coordinates). The response and
    the run record carry texture_gate {dropped_strokes, dropped_ink_mm, dropped_ink_fraction}; the adaptive readouts
    (p2, Canny high/low, gate density threshold) are in twotone.readouts and in the run provenance."""
    return _handle(request.get_json(silent=True), sheet=False, mode="twotone")


@app.route("/api/twopen_keytint", methods=["POST"])
def api_twopen_keytint():
    """Opt-in "Black Line + Blue Tone" (key + tint): PHOTO -> the app's own bwphoto job (run, captured) ->
    explicit global separation (ccplotter/twopen_keytint.py) -> two mm layers -> the same twopen pipeline
    (gcode x2, preview, run record, headers, refusals, tip window). PASS ORDER: pass 1 = BLUE, pass 2 = BLACK.
    Body: {image: <path to a photo>  OR  image_b64: <base64 file bytes>, blue_pen_id (default bic_cristal_blue),
    black_pen_id (default bic_cristal_black), blue_amount (ONE global tint amount, default 0.375, clamped to the
    range 0..0.5), paper ("257x182" default), margin (10), debug (write the mask / layer PNGs), and the twopen
    placement fields (offset_x, offset_y, paper_rot, tip_window, microlift, end_policy,
    quiet_fans, motion_smoothing)}. Pen Z / speeds come from each pen's live profile, never the body.
    /api/process, /api/twopen, /api/twotone and every existing mode are untouched.

    TWO INPUT MODES. (1) CANVAS (the UI): send the normal Generate body (items with exactly one raster drawing, paper,
    margin, offset_x/offset_y, paper_keepout, registered_paper, paper_rot and every setting). It is handed UNCHANGED to the
    plain bwphoto job, so the placement and the hole-strip keep-out (composite.py clips after routing) are the plain job's;
    both layers inherit them, and reach is refused per pass at gcode generation (422). (2) IMAGE: image / image_b64 with a
    default placement and NO keep-out (use canvas mode for a registered paper).
    The two-pen route takes a photo (like /api/twotone), so it is a sibling route and not a `variant` of
    /api/twopen, whose contract stays "two ready mm SVG layers in"; /api/twopen's behaviour cannot change."""
    return _handle(request.get_json(silent=True), sheet=False, mode="keytint")


def _handle(body, sheet, mode=None):
    if not isinstance(body, dict):
        return jsonify({"error": "JSON object body required"}), 400
    t0 = time.time()
    rid = uuid4().hex[:8]
    kt_prep = None
    if mode == "keytint":
        # The plain bwphoto job is run through /api/process, which takes _PROCESS_LOCK itself, so this step
        # must run BEFORE this handler takes the lock (the lock is not re-entrant).
        try:
            kt_prep = _keytint_prepare(body, rid)
        except TwoPenRefusal as e:
            return jsonify({"error": str(e), "refused": True}), e.status
        except Exception as e:
            traceback.print_exc()
            return jsonify({"error": f"Two-pen pipeline failed: {e}"}), 500
    if not _PROCESS_LOCK.acquire(blocking=False):
        return jsonify({"error": "busy", "retry": False}), 429
    tt_info = None
    kt_info = None
    try:
        try:
            build_body = body
            if mode == "twotone":
                build_body, tt_info = _twotone_body(body, rid)
            elif mode == "keytint":
                build_body, kt_info = _keytint_body(body, rid, kt_prep)
            elif sheet:
                from ccplotter.calibration_twopen import sheet_body
                from ccplotter.cal import load_pen_profiles
                keep = {k: body[k] for k in ("offset_x", "offset_y", "microlift", "end_policy",
                                             "quiet_fans", "motion_smoothing") if k in body}
                variant = str(body.get("variant", "B")).upper()
                if variant not in ("A", "B"):
                    return jsonify({"error": "variant must be 'A' (same-pen swap repeatability: "
                                             "blue / bic_cristal_blue_b) or 'B' (blue / black)"}), 400
                # Sheet A swaps the SAME pen (profile copy bic_cristal_blue_b, which the user must
                # add; this route never writes a profile). Default ids follow the variant.
                bid = body.get("blue_pen_id") or "bic_cristal_blue"
                kid = body.get("black_pen_id") or ("bic_cristal_blue_b" if variant == "A" else "bic_cristal_black")
                build_body, _ = sheet_body(bid, kid, load_pen_profiles().get("profiles", {}),
                                           variant=variant, **keep)
            r = build_twopen(build_body, rid=rid)
        except TwoPenRefusal as e:
            return jsonify({"error": str(e), "refused": True}), e.status
        except Exception as e:
            traceback.print_exc()
            return jsonify({"error": f"Two-pen pipeline failed: {e}"}), 500
        g_blue, g_black, prev = r["files"]["blue"], r["files"]["black"], r["preview"]
        rec = {"type": ("twotone" if mode == "twotone" else "twopen_keytint" if mode == "keytint"
                        else ("twopen_calsheet" if sheet else "twopen")), "mode": "twopen",
               "blue_pen_id": r["blue_id"], "black_pen_id": r["black_id"],
               "passes": [{k: p[k] for k in ("pass", "color", "pen_id", "strokes", "z_down_abs",
                                             "z_touch_abs", "reach_profile", "file", "time_est")} for p in r["passes"]],
               "source_ids": []}
        if tt_info:
            rec["twotone"] = tt_info
            rec["texture_gate"] = tt_info["texture_gate"]
        if kt_info:
            rec["keytint"] = {k: kt_info[k] for k in ("blue_amount", "pass_order", "layer_stats", "separation", "blue_trap")}
            if kt_info.get("stay_down_over_ink"):
                rec["keytint"]["stay_down_over_ink"] = kt_info["stay_down_over_ink"]
            if kt_info.get("hatched_blue"):
                rec["keytint"]["hatched_blue"] = kt_info["hatched_blue"]
        resolved = {"blue": {"pen_id": r["blue_id"], "profile": r["blue_profile"]},
                    "black": {"pen_id": r["black_id"], "profile": r["black_profile"]},
                    "passes": r["passes"],
                    "placement": r["placement"],
                    "placement_offsets_mm": {"blue": r["passes"][0]["nozzle_offset_mm"],
                                             "black": r["passes"][1]["nozzle_offset_mm"],
                                             "shared_pen_target": [r["placement"]["offset_x"],
                                                                   r["placement"]["offset_y"]]},
                    "pen_offsets_mm": {"blue": r["passes"][0]["pen_offset_mm"],
                                       "black": r["passes"][1]["pen_offset_mm"]},
                    **({"twotone": {"readouts": tt_info["readouts"], "texture_gate": tt_info["texture_gate"],
                                    "hash": tt_info["hash"], "blue_preset": tt_info["blue_preset"],
                                    "placed_mm": tt_info["placed_mm"]}} if tt_info else {}),
                    **({"keytint": kt_info} if kt_info else {})}
        # MAIN-FLOW MODE ("Black Line + Blue Tone (2 pens)" in the mode selector): body {main_flow: true, job_type}.
        # A job_type "preview" is a live preview -- NO run record / provenance / stamped copies (same as a plain preview,
        # which is not archived either); only job_type "gcode" archives. A body without main_flow archives as a normal job.
        main_flow = bool(kt_info) and bool(body.get("main_flow"))
        preview_only = main_flow and body.get("job_type") == "preview"
        if not preview_only:
            try:
                prov = build_run_provenance(body, body, r["blue_id"], r["blue_profile"], resolved)
                _runs_add(rec, copy_files={"gcode_blue": g_blue, "gcode_black": g_black, "preview": prev,
                                      **({"preview_png": kt_info["preview_png"]} if kt_info else {})},
                          provenance=prov, stamp_gcode=True, rid=rid,
                          stamp_labels=("gcode_blue", "gcode_black"))
            except Exception as e:
                return jsonify({"error": f"run record failed after generation: {e}"}), 500
        sheet_extra = {}
        if sheet:
            try:
                shas = _sheet_provenance_shas(rid, r, variant)
                prof = {"blue": r["blue_profile"], "black": r["black_profile"]}
                sheet_extra = {
                    "variant": variant, "gcode_sha256": shas,
                    "provenance_file": f"run_provenance/{rid}.json",
                    "canvas_preview_svg": _sheet_canvas_preview(r, rid),
                    "pass_colors": list(SHEET_PASS_COLORS),
                    "download": [{"pass": p["pass"], "pen_id": p["pen_id"],
                                  "pen_label": (prof[p["color"]] or {}).get("label") or p["pen_id"],
                                  "url": f"/work/{p['file']}",
                                  "download_name": f"m10reg_{variant}_pass{p['pass']}_{p['pen_id']}.gcode"}
                                 for p in r["passes"]]}
            except Exception as e:
                traceback.print_exc()
                return jsonify({"error": f"sheet provenance/preview failed after generation: {e}"}), 500
        return jsonify({
            **sheet_extra,
            "ok": True, "run_id": rid, "elapsed_s": round(time.time() - t0, 2),
            "paper": f"{r['paper_w']}x{r['paper_h']}mm",
            "gcode_files": [{"pass": p["pass"], "color": p["color"], "pen_id": p["pen_id"],
                             "file": p["file"],
                             "run_file": (None if preview_only else f"runs/{rid}/gcode_{p['color']}.gcode"),
                             "z_down_abs": p["z_down_abs"], "z_touch_abs": p["z_touch_abs"],
                             "strokes": p["strokes"], "reach_validated": p["reach_validated"],
                             "time_est": p["time_est"]}
                            for p in r["passes"]],
            "preview_file": f"{TWOPEN_DIRNAME}/{prev.name}",
            "passes": r["passes"],
            **({"twotone": tt_info, "texture_gate": tt_info["texture_gate"]} if tt_info else {}),
            **({"keytint": kt_info, "preview_png": kt_info["preview_png_url"]} if kt_info else {}),
            **({"ui": _keytint_ui(body, rid, r, kt_info, kt_prep, preview_only, time.time() - t0)} if main_flow else {})})
    finally:
        _PROCESS_LOCK.release()


def _twotone_body(body, rid):
    """Photo -> two layer SVGs on disk (WORK_DIR/twotone/<rid>/) -> a plain twopen body. Raises TwoPenRefusal (400)
    for a bad image / preset / paper so they come back as 4xx, never 500."""
    import base64
    from pathlib import Path
    from ccplotter import twotone as tt
    from ccplotter.config import WORK_DIR
    from ccplotter.twopen import _parse_paper
    paper_w, paper_h = _parse_paper(body.get("paper", "257x182"))
    try:
        margin = float(body.get("margin", tt.DEFAULT_MARGIN_MM))
    except Exception:
        raise TwoPenRefusal("margin must be a number")
    if margin < 0 or margin * 2 >= min(paper_w, paper_h):
        raise TwoPenRefusal("margin does not fit the paper")
    preset = str(body.get("blue_preset", "LIGHT")).upper()
    if preset not in tt.PRESETS:
        raise TwoPenRefusal(f"blue_preset must be one of {tt.PRESETS}")
    jobdir = Path(WORK_DIR) / "twotone" / rid
    jobdir.mkdir(parents=True, exist_ok=True)
    if body.get("image_b64"):
        try:
            data = base64.b64decode(body["image_b64"], validate=False)
        except Exception:
            raise TwoPenRefusal("image_b64 is not valid base64")
        src = jobdir / "upload.img"
        src.write_bytes(data)
    elif body.get("image"):
        src = Path(str(body["image"]))
        if not src.is_file() or src.suffix.lower() not in (".jpg", ".jpeg", ".png", ".bmp", ".tif", ".tiff", ".webp"):
            raise TwoPenRefusal("image is not an existing photo file")
    else:
        raise TwoPenRefusal("image (path) or image_b64 is required")
    try:
        L = tt.generate_layers(src, page=(paper_w, paper_h), margin=margin, blue_preset=preset)
    except Exception as e:
        raise TwoPenRefusal(f"two-tone generation failed: {e}")
    if not L["blue"] or not L["black"]:
        raise TwoPenRefusal("the recipe produced an empty layer for this image")
    bsvg, ksvg = jobdir / "blue_mm.svg", jobdir / "black_mm.svg"
    bsvg.write_text(tt.to_svg(L["blue"], (paper_w, paper_h), "blue_pass_first", tt.BLUE_COLOR), encoding="ascii")
    ksvg.write_text(tt.to_svg(L["black"], (paper_w, paper_h), "black_pass_last", tt.BLACK_COLOR), encoding="ascii")
    keep = ("blue_pen_id", "black_pen_id", "offset_x", "offset_y", "scale", "rot", "dx", "dy", "paper_rot",
            "tip_window", "microlift", "end_policy", "quiet_fans", "motion_smoothing")
    build_body = {k: body[k] for k in keep if k in body}
    build_body.update({"blue_svg": str(bsvg), "black_svg": str(ksvg), "paper": f"{paper_w:g}x{paper_h:g}"})
    import cv2, json as _json
    cv2.imwrite(str(jobdir / "texture_gate.png"), (L["gate_map"].astype("uint8") * 255))
    (jobdir / "texture_gate_dropped.json").write_text(_json.dumps(
        {"note": "black strokes dropped by the texture gate (mm page coordinates)",
         "strokes": [[[round(float(x), 3), round(float(y), 3)] for x, y in s_] for s_ in L["gate_dropped"]]}), encoding="ascii")
    info = {"recipe": "frozen v16 (inside_join + closing + solid_overlap)", "blue_preset": preset, "hash": L["hash"],
            "texture_gate": L["texture_gate"], "readouts": L["readouts"],
            "gate_artefacts": {"map_png": str(jobdir / "texture_gate.png"),
                               "dropped_json": str(jobdir / "texture_gate_dropped.json")},
            "strokes": {"blue": len(L["blue"]), "black_lines": len(L["lines"]), "black_shadow": len(L["shadow"])},
            "placed_mm": [round(v, 3) for v in L["placed_mm"]], "page_mm": list(L["page"]), "margin_mm": margin,
            "layers": {"blue": str(bsvg), "black": str(ksvg)}}
    return build_body, info


def _sniff_suffix(data):
    """File extension for uploaded bytes (the bwphoto job keys its loader on the extension)."""
    import io
    from PIL import Image
    try:
        fmt = (Image.open(io.BytesIO(data)).format or "").upper()
    except Exception:
        raise TwoPenRefusal("image_b64 is not a decodable image")
    ext = {"JPEG": ".jpg", "PNG": ".png", "BMP": ".bmp", "TIFF": ".tif", "WEBP": ".webp"}.get(fmt)
    if not ext:
        raise TwoPenRefusal(f"unsupported image format {fmt!r}")
    return ext


def _keytint_prepare(body, rid):
    """Validate the request and run the PLAIN bwphoto job (captured by ccplotter/twopen_keytint.py). Runs BEFORE the
    process lock is taken (the plain job takes it itself). Raises TwoPenRefusal (4xx) for anything the caller got wrong."""
    import base64
    from ccplotter import twopen_keytint as kt
    from ccplotter.config import WORK_DIR
    from ccplotter.twopen import _parse_paper, resolve_pens
    canvas = "items" in body
    paper_spec_in = body.get("paper", "b5" if canvas else kt.DEFAULT_PAPER)
    paper_w, paper_h = _parse_paper(paper_spec_in)
    try:
        margin = float(body.get("margin", kt.DEFAULT_MARGIN_MM))
    except Exception:
        raise TwoPenRefusal("margin must be a number")
    if margin < 0 or margin * 2 >= min(paper_w, paper_h):
        raise TwoPenRefusal("margin does not fit the paper")
    margin = max(0.0, min(margin, min(paper_w, paper_h) / 2 - 1))     # the same clamp /api/process applies
    try:
        a = kt.clamp_blue_amount(body.get("blue_amount"))
    except kt.KeytintError as e:
        raise TwoPenRefusal(str(e), e.status)
    # Opt-in "Blue margin under black" (T1 + X + F). Absent / false -> the unchanged path. One parse for every entry path.
    bt = body.get("blue_trap", False)
    if bt is None or bt == "":
        bt = False
    if not isinstance(bt, bool):
        raise TwoPenRefusal("blue_trap must be true or false")
    # Opt-in "Stay down over ink (no stray lines)": each layer's pen-up travels that lie wholly inside that layer's own
    # ink become pen-down connectors. Same parse, absent / false -> the unchanged path, for every entry path.
    sd = body.get("stay_down_over_ink", False)
    if sd is None or sd == "":
        sd = False
    if not isinstance(sd, bool):
        raise TwoPenRefusal("stay_down_over_ink must be true or false")
    # Opt-in "Hatched blue (lighter, fewer pen lifts)" (arm B3s): the blue layer is a density-modulated hatch. Same parse, absent / false -> unchanged.
    hb = body.get("hatched_blue", False)
    if hb is None or hb == "":
        hb = False
    if not isinstance(hb, bool):
        raise TwoPenRefusal("hatched_blue must be true or false")
    pens = resolve_pens({"blue_pen_id": body.get("blue_pen_id") or kt.DEFAULT_BLUE_PEN,
                         "black_pen_id": body.get("black_pen_id") or kt.DEFAULT_BLACK_PEN})
    jobdir = Path(WORK_DIR) / "keytint" / rid
    jobdir.mkdir(parents=True, exist_ok=True)
    item, body_extra = None, {}
    # One rule for every entry path -- the body's connector_distance (the routes/core.py expression), absent -> 0.0.
    # Canvas mode forwards the whole body; the image / image_b64 paths forward just this key.
    try:
        _cd = float(body.get("connector_distance", body.get("join_nearby", 0.0)))
    except (TypeError, ValueError):
        raise TwoPenRefusal("connector_distance must be a number")
    if canvas:
        # CANVAS MODE (the UI): a normal Generate body. Its placement fields (offsets, paper, margin, paper_keepout,
        # registered_paper, paper_rot, item geometry, every setting) reach the plain bwphoto job UNCHANGED, so the
        # plain job and both layers share one placement and one keep-out (applied server-side by composite).
        items = body.get("items")
        if not isinstance(items, list) or len(items) != 1 or not isinstance(items[0], dict):
            raise TwoPenRefusal("Black Line + Blue Tone takes exactly one drawing")
        item = items[0]
        if item.get("fill_page") or item.get("true_size") or item.get("registration_marks"):
            raise TwoPenRefusal("fill-page / true-size / registration items are not supported by Black Line + Blue Tone")
        cands = [m for m in Path(WORK_DIR).glob(f"src_{item.get('id')}.*")
                 if m.suffix.lower() in (".jpg", ".jpeg", ".png", ".bmp", ".tif", ".tiff", ".webp")
                 and "_render" not in m.name and not m.name.endswith("_traced.svg")]
        if not cands or not str(item.get("id", "")).isalnum():
            raise TwoPenRefusal("the drawing is not an uploaded raster image")
        src = cands[0]
        drop = {"items", "style", "job_type", "pen_id", "debug", "blue_amount", "blue_pen_id", "black_pen_id",
                "image", "image_b64", "paper", "margin", "main_flow", "blue_trap", "stay_down_over_ink", "hatched_blue"}
        body_extra = {k: v for k, v in body.items() if k not in drop}
    elif body.get("image_b64"):
        try:
            data = base64.b64decode(body["image_b64"], validate=False)
        except Exception:
            raise TwoPenRefusal("image_b64 is not valid base64")
        src = jobdir / f"upload{_sniff_suffix(data)}"
        src.write_bytes(data)
        body_extra = {"connector_distance": _cd}
    elif body.get("image"):
        src = Path(str(body["image"]))
        if not src.is_file() or src.suffix.lower() not in (".jpg", ".jpeg", ".png", ".bmp", ".tif", ".tiff", ".webp"):
            raise TwoPenRefusal("image is not an existing photo file")
        body_extra = {"connector_distance": _cd}
    else:
        raise TwoPenRefusal("image (path), image_b64 or items is required")
    try:
        prep = kt.capture_plain_bwphoto(src, jobdir, paper_w=paper_w, paper_h=paper_h, margin=margin, pen_id=pens[2],
                                        paper_spec=(paper_spec_in if canvas else f"{paper_w:g}x{paper_h:g}"),
                                        body_extra=body_extra, item=item)
    except kt.KeytintError as e:
        raise TwoPenRefusal(str(e), e.status)
    return {"prep": prep, "jobdir": jobdir, "blue_amount": a, "pens": pens, "paper": (paper_w, paper_h), "blue_trap": bt,
            "stay_down_over_ink": sd, "hatched_blue": hb}


def _plain_reach_warnings(plain_warnings):
    """The plain bwphoto job's registered-paper reach warning (stats_warnings.py: 'falls outside the pen's
    reachable area') is carried into the keytint response so the UI shows it. A keep-out CLIP is silent in /api/process
    (no warning is produced, only stats["paper_keepout_clip"]), so it is silent here too, matching /api/process."""
    out = []
    for w in plain_warnings or []:
        msg = w.get("msg", "") if isinstance(w, dict) else str(w)
        if "reachable area" in msg:
            out.append(msg)
    return out


SAVE_NAME_SUFFIX = {"blue": "_1_blue.gcode", "black": "_2_black.gcode"}     # plot order explicit in the file name


def _keytint_ui(body, rid, r, kt_info, kp, preview_only, elapsed_s):
    """Main-flow mode: a /api/process-shaped block (paper, preview_file, stats, item_bboxes/item_geometry keyed by the
    CANVAS drawing id, warnings) so the UI's one applyProcessResult path renders it, plus per-pass stats and the exact
    files the Save action writes (pass 1 blue, pass 2 black; names carry the order). Time figures are model (b)."""
    stats = kt_info["layer_stats"]
    passes = []
    for p in r["passes"]:
        c = p["color"]
        f = _work_dir() / p["file"]
        passes.append({"pass": p["pass"], "color": c, "pen_id": p["pen_id"], "pen_label": kt_info["pen_labels"][c],
                       "strokes": stats[c]["strokes"], "pen_lifts": stats[c]["pen_lifts"], "draw_mm": stats[c]["draw_mm"],
                       "draw_m": round(stats[c]["draw_mm"] / 1000.0, 2),
                       "minutes": p["time_est"]["minutes"], "time_label": p["time_est"]["label"],
                       "z_touch_abs": p["z_touch_abs"], "z_down_abs": p["z_down_abs"],
                       "size_kb": round(f.stat().st_size / 1024.0, 1),
                       "work_file": p["file"], "run_file": (None if preview_only else f"runs/{rid}/gcode_{c}.gcode"),
                       "save_suffix": SAVE_NAME_SUFFIX[c], "pass_color": kt_info["pass_colors"][c]})
    items = body.get("items") or [{}]
    item_id = str(items[0].get("id", ""))
    ig = kp["prep"].get("item_geometry")
    if ig:
        # The plain job ran under an internal item id; the UI's sameFitItem() compares item_settings.id with the canvas
        # item it SENT, so without this Fit / Fill Page / auto-fit refuse ("Process this drawing before fitting").
        ig = {**ig, "item_settings": {**(ig.get("item_settings") or {}), "id": item_id}}
    bbs = list((kp["prep"].get("item_bboxes") or {}).values())
    warn = []
    for w in (kp["prep"]["response_summary"].get("warnings") or []):
        msg = w.get("msg", "") if isinstance(w, dict) else str(w)
        if "reachable area" in msg:
            warn.append(dict(w) if isinstance(w, dict) else {"level": "danger", "msg": msg})
    for m in kt_info["warnings"]:
        if not any(m == w.get("msg") for w in warn):
            warn.append({"level": "warning", "msg": m})
    return {"paper": f"{r['paper_w']:g}x{r['paper_h']:g}mm", "preview_file": f"{TWOPEN_DIRNAME}/{r['preview'].name}",
            "stroke_count": sum(x["strokes"] for x in passes), "estimated_z_moves": 2 * sum(x["pen_lifts"] for x in passes),     # /api/process definition: 2 Z moves per stroke (D1631a)
            "draw_length_mm": sum(x["draw_mm"] for x in passes),
            "estimated_plot_time_min": round(sum(x["minutes"] for x in passes), 1),
            "file_size_kb": round(sum(x["size_kb"] for x in passes), 1), "elapsed_s": round(elapsed_s, 1),
            "item_bboxes": ({item_id: bbs[0]} if bbs else {}), "item_geometry": ({item_id: ig} if ig else {}),
            "warnings": warn, "trace_info": {"mode": "Black Line + Blue Tone (bwphoto + key/tint separation)",
                                             "effective_res": kt_info["separation"].get("effective_res")},
            "gcode_file": None, "run_id": (None if preview_only else rid), "preview_only": bool(preview_only),
            "keytint_ui": {"run_id": (None if preview_only else rid), "blue_amount": kt_info["blue_amount"],
                           "run_dir": (None if preview_only else str((_work_dir() / "runs" / rid).resolve())),
                           "passes": passes, "time_label": passes[0]["time_label"],
                           "pass_order": "pass 1 = blue, pass 2 = black"}}


def _work_dir():
    from ccplotter.config import WORK_DIR
    return Path(WORK_DIR)


def _keytint_body(body, rid, kp):
    """Captured plain job -> separation -> two routed layer SVGs on disk -> a plain twopen body."""
    from ccplotter import twopen_keytint as kt
    from ccplotter.composite import preview_pen_width_mm
    bid, bprof, kid, kprof = kp["pens"]
    paper_w, paper_h = kp["paper"]
    widths = {"blue": preview_pen_width_mm(bprof, bprof), "black": preview_pen_width_mm(kprof, kprof)}
    try:
        g = kt.generate_layers(kp["prep"], kp["blue_amount"], kp["jobdir"], widths, debug=bool(body.get("debug", False)),
                               blue_trap=bool(kp.get("blue_trap")), blue_fill_mm=bprof.get("fill_mm"),
                               stay_down_over_ink=bool(kp.get("stay_down_over_ink")),
                               hatched_blue=bool(kp.get("hatched_blue")))
    except kt.KeytintError as e:
        raise TwoPenRefusal(str(e), e.status)
    if not g["layers"]["blue"] or not g["strokes"]["blue"]:
        raise TwoPenRefusal(f"the blue layer is empty at blue_amount={kp['blue_amount']:g}; raise blue_amount "
                            f"(0 draws no tint)")
    if not g["layers"]["black"] or not g["strokes"]["black"]:
        raise TwoPenRefusal("the recipe produced an empty black layer for this image")
    # item scale/rot/dx/dy are already baked into the layers (the plain job's placement); never re-applied here
    keep = ("offset_x", "offset_y", "paper_rot", "tip_window", "microlift", "end_policy", "quiet_fans", "motion_smoothing")
    build_body = {k: body[k] for k in keep if k in body}
    build_body.update({"blue_pen_id": bid, "black_pen_id": kid, "paper": f"{paper_w:g}x{paper_h:g}",
                       "blue_svg": str(g["layers"]["blue"]), "black_svg": str(g["layers"]["black"])})
    warnings = _plain_reach_warnings(kp["prep"]["response_summary"].get("warnings"))
    if abs(float(bprof.get("fill_mm", 0)) - float(kprof.get("fill_mm", 0))) > 1e-9:
        warnings.append(f"blue fill_mm {bprof.get('fill_mm')} != black fill_mm {kprof.get('fill_mm')}: both layers are "
                        "traced at the black pen's pass pitch (the plain bwphoto job's options)")
    info = {"recipe": "key + tint (D0 darks, strip in black Q1-k, tentative)", "blue_amount": kp["blue_amount"],
            "pass_order": ["blue", "black"], "layer_stats": g["stats"], "separation": g["info"], "warnings": warnings,
            "pen_labels": {"blue": bprof.get("label") or bid, "black": kprof.get("label") or kid},
            "pass_colors": {"blue": "#1f4fd8", "black": "#111111"},
            "layers": {c: str(p) for c, p in g["layers"].items()},
            "debug_files": g["debug_files"], "preview_png": str(g["preview_png"]),
            "preview_png_url": f"keytint/{rid}/{Path(g['preview_png']).name}",
            "plain_job_routed_svg": str(kp["prep"]["plain_routed_svg"]),
            "blue_trap": g["info"]["blue_trap"],
            **({"hatched_blue": g["info"]["hatched_blue"]} if g["info"].get("hatched_blue") else {}),
            **({"stay_down_over_ink": g["info"]["stay_down_over_ink"]} if g["info"].get("stay_down_over_ink") else {})}       # option + constants + invariants, recorded in the run record / provenance
    return build_body, info
